package main

import (
	"fmt"
	"go/types"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/nskaggs/perfuncted/scripts/internal/cliname"

	"golang.org/x/tools/go/packages"
)

func uniq(xs []string) []string {
	m := map[string]bool{}
	out := []string{}
	for _, x := range xs {
		if x == "" {
			continue
		}
		if !m[x] {
			m[x] = true
			out = append(out, x)
		}
	}
	slices.Sort(out)
	return out
}

var commonPrefixes = []string{
	"Mouse", "Key", "Grab", "Find", "WaitFor", "Wait", "Get", "Set", "List", "Active", "Activate", "Press", "Scroll", "Close", "Pointer",
}

func candidatesFromMethod(name string) []string {
	c := []string{}
	c = append(c, cliname.Hyphenate(name))
	// plain lowercase
	c = append(c, strings.ToLower(name))

	// try stripping common prefixes
	for _, p := range commonPrefixes {
		if strings.HasPrefix(name, p) {
			// also allow the prefix itself as a candidate (e.g. ActiveTitle -> "active")
			c = append(c, strings.ToLower(p))
			s := strings.TrimPrefix(name, p)
			if s != "" {
				c = append(c, cliname.Hyphenate(s))
				c = append(c, strings.ToLower(s))
			}
		}
	}

	// special-case Hash suffix -> allow plain "hash"
	if strings.HasSuffix(name, "Hash") {
		c = append(c, "hash")
		base := strings.TrimSuffix(name, "Hash")
		c = append(c, cliname.Hyphenate(base))
	}

	return uniq(c)
}

func methodsForType(pkg *packages.Package, typeName string) ([]string, error) {
	obj := pkg.Types.Scope().Lookup(typeName)
	if obj == nil {
		return nil, fmt.Errorf("type %s not found in package %s", typeName, pkg.PkgPath)
	}
	named, ok := obj.Type().(*types.Named)
	if !ok {
		return nil, fmt.Errorf("%s is not a named type", typeName)
	}

	// Use pointer method set to be permissive (includes both pointer/value receivers)
	ms := types.NewMethodSet(types.NewPointer(named))
	set := map[string]bool{}
	for i := 0; i < ms.Len(); i++ {
		sel := ms.At(i)
		m := sel.Obj()
		// only exported
		if m.Exported() {
			set[m.Name()] = true
		}
	}
	out := make([]string, 0, len(set))
	for k := range set {
		out = append(out, k)
	}
	slices.Sort(out)
	return out, nil
}

func skipMethodForCLISync(name string) bool {
	if strings.HasSuffix(name, "Context") || name == "Close" {
		return true
	}
	switch name {
	case "FindColor",
		"GetMultiplePixels",
		"IterateWindows",
		"LocateExact",
		"ScanFor",
		"WaitFor",
		"WaitForChange",
		"WaitForFn",
		"WaitForSettle",
		"WaitForWindow",
		"Wait",
		"Sync":
		return true
	default:
		return false
	}
}

func main() {
	os.Exit(verifyCLISync(".", "docs-cli"))
}

// verifyCLISync checks the actual exported bundle API against generated CLI
// documentation. It returns the command exit status, enabling end-to-end
// verification without terminating the test runner.
func verifyCLISync(moduleDir, docsDir string) int { //nolint:gocyclo
	// map CLI group -> perfuncted bundle type
	bundleTypes := map[string]string{
		"screen":    "ScreenBundle",
		"input":     "InputBundle",
		"window":    "WindowBundle",
		"clipboard": "ClipboardBundle",
	}

	cfg := &packages.Config{Mode: packages.NeedName | packages.NeedTypes, Dir: moduleDir}
	pkgs, err := packages.Load(cfg, "./...")
	if err != nil {
		fmt.Fprintln(os.Stderr, "loading packages:", err)
		return 2
	}

	var perfPkg *packages.Package
	for _, p := range pkgs {
		if p.PkgPath == "github.com/nskaggs/perfuncted" {
			perfPkg = p
			break
		}
	}
	if perfPkg == nil {
		fmt.Fprintln(os.Stderr, "could not find perfuncted package in module")
		return 2
	}

	methods := map[string][]string{}
	for grp, tname := range bundleTypes {
		m, methodErr := methodsForType(perfPkg, tname)
		if methodErr != nil {
			// If type not found, continue but warn
			fmt.Fprintf(os.Stderr, "warning: %v\n", methodErr)
			methods[grp] = []string{}
			continue
		}
		methods[grp] = m
	}

	// collect docs-cli commands
	docsFiles, err := filepath.Glob(filepath.Join(docsDir, "pf_*.md"))
	if err != nil {
		fmt.Fprintln(os.Stderr, "globbing docs-cli:", err)
		return 2
	}
	docs := map[string]map[string]bool{}
	re := regexp.MustCompile(`^pf_([a-z0-9-]+)_(.+)\.md$`)
	for _, f := range docsFiles {
		base := filepath.Base(f)
		if base == "pf.md" || strings.HasPrefix(base, "pf_completion") || base == "pf_docs.md" {
			continue
		}
		m := re.FindStringSubmatch(base)
		if m == nil {
			// skip pf_input.md and other group pages
			continue
		}
		grp := m[1]
		// doc files use underscores for multi-word commands (e.g. pf_input_scroll_right.md).
		// Normalize to hyphens so it matches candidatesFromMethod output.
		cmd := strings.ReplaceAll(m[2], "_", "-")
		if docs[grp] == nil {
			docs[grp] = map[string]bool{}
		}
		docs[grp][cmd] = true
	}

	// Whitelist expected discrepancies: manual CLI wrappers that use Context methods
	// These are valid CLI commands but use Context methods which are intentionally skipped
	// in the CLI/API sync check to focus on the autogenerated API surface.
	whitelist := map[string]map[string]bool{
		"window": {
			// Composite stable-ID commands have no one-to-one bundle methods.
			"activate-id":   true,
			"close-id":      true,
			"activate":      true,
			"close":         true,
			"find-by-title": true,
			"fullscreen":    true,
			"get-geometry":  true,
			"is-visible":    true,
			"iterate":       true,
			"maximize":      true,
			"minimize":      true,
			"move":          true,
			"resize":        true,
			"unfullscreen":  true,
			"watch":         true,
			"wait-close":    true,
			"wait-for":      true,
		},
		"screen": {
			"pixel":               true,
			"resolution":          true,
			"grab-hash":           true,
			"watch":               true,
			"wait-for":            true,
			"wait-for-change":     true,
			"wait-for-fn":         true,
			"wait-for-settle":     true,
			"get-multiple-pixels": true,
		},
		"input": {
			// Coordinate verification and file-selection helpers compose multiple APIs.
			"click-screen": true,
			"click-window": true,
			"select-file":  true,
			"sync":         true,
		},
	}
	// Whitelist expected API-only methods that intentionally have no direct docs-cli command.
	apiOnlyWhitelist := map[string]map[string]bool{
		"screen": {
			"Capture":       true,
			"CaptureRegion": true,
		},
		"window": {
			"Events":  true,
			"Restore": true,
		},
	}

	missingInAPI := []string{}
	missingInCLI := []string{}

	// Check docs -> API: every docs command should map to at least one method candidate
	for grp, cmds := range docs {
		// only enforce for known bundles
		if _, ok := bundleTypes[grp]; !ok {
			continue
		}
		mset := map[string]bool{}
		for _, mn := range methods[grp] {
			if skipMethodForCLISync(mn) {
				continue
			}
			for _, c := range candidatesFromMethod(mn) {
				mset[c] = true
			}
		}
		for cmd := range cmds {
			// Skip whitelisted commands that are expected to not match
			if whitelist[grp] != nil && whitelist[grp][cmd] {
				continue
			}
			if !mset[cmd] {
				missingInAPI = append(missingInAPI, fmt.Sprintf("docs-cli: %s %s", grp, cmd))
			}
		}
	}

	// Check API -> docs: every exported method should have at least one docs command
	for grp, mlist := range methods {
		if _, ok := bundleTypes[grp]; !ok {
			continue
		}
		for _, mn := range mlist {
			if skipMethodForCLISync(mn) {
				continue
			}
			if apiOnlyWhitelist[grp] != nil && apiOnlyWhitelist[grp][mn] {
				continue
			}
			ok := false
			for _, c := range candidatesFromMethod(mn) {
				if docs[grp] != nil && docs[grp][c] {
					ok = true
					break
				}
			}
			if !ok {
				missingInCLI = append(missingInCLI, fmt.Sprintf("api-only: %s.%s", grp, mn))
			}
		}
	}

	if len(missingInAPI) == 0 && len(missingInCLI) == 0 {
		fmt.Println("Basic CLI/API sync check: OK")
		return 0
	}

	fmt.Println("CLI/API sync issues detected:")
	if len(missingInAPI) > 0 {
		fmt.Println("\nCLI doc commands with no matching API method (possible doc-only CLI):")
		for _, s := range missingInAPI {
			fmt.Println("  -", s)
		}
	}
	if len(missingInCLI) > 0 {
		fmt.Println("\nExported API methods with no matching CLI doc (possible API-only):")
		for _, s := range missingInCLI {
			fmt.Println("  -", s)
		}
	}

	fmt.Println("\nThis is a best-effort check. Some commands map to multiple API calls or use different names.")
	fmt.Println("If these warnings are expected, whitelist them or improve mapping rules in scripts/verify_cli_api.go")

	if len(missingInAPI) > 0 || len(missingInCLI) > 0 {
		return 1
	}
	return 0
}
