func TestAutogeneratedCommandsPropagateAuthorizationFailureBeforeBackendUse(t *testing.T) {
	denied := errors.New("synthetic session access denied")
	calls := 0
	open := func(context.Context) (*perfuncted.Session, error) { calls++; return nil, denied }
	for _, factory := range []func(sessionOpener) []*cobra.Command{autogenScreenCommands, autogenInputCommands} {
		for _, cmd := range factory(open) {
			t.Run(cmd.Name(), func(t *testing.T) {
				var out bytes.Buffer
				cmd.SilenceUsage = true
				cmd.SetOut(&out)
				if cmd.Name() == "type-literal" {
					cmd.SetArgs([]string{"private data"})
				} else {
					cmd.SetArgs(nil)
				}
				err := cmd.ExecuteContext(context.Background())
				if !errors.Is(err, denied) || out.Len() != 0 {
					t.Fatalf("unauthorized generated command accepted: err=%v out=%q", err, out.String())
				}
			})
		}
	}
	if calls != 4 {
		t.Fatalf("expected four explicit authorization attempts; got %d", calls)
	}
}

func TestAutogeneratedWaitCommandsRejectMalformedUserInputBeforeCapture(t *testing.T) {
	frames := 0
	open := func(ctx context.Context) (*perfuncted.Session, error) {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		screen := &pftest.Screenshotter{GrabFunc: func(context.Context, image.Rectangle) (image.Image, error) {
			frames++
			return pftest.SolidImage(2, 2, color.RGBA{A: 255}), nil
		}}
		return pftest.New(screen, nil, nil, nil), nil
	}
	for _, tc := range []struct {
		name string
		args []string
		want string
	}{
		{"invalid rectangle", []string{"wait-for-no-change", "--rect", "invalid"}, "rect"},
		{"invalid polling interval", []string{"wait-for-no-change", "--rect", "0,0,2,2", "--poll", "not-a-duration"}, "duration"},
		{"invalid from rectangle", []string{"wait-for-no-change-from", "--rect", "invalid", "--initial", "2"}, "rect"},
		{"invalid initial hash", []string{"wait-for-no-change-from", "--rect", "0,0,2,2", "--initial", "invalid"}, "hash"},
		{"invalid from polling", []string{"wait-for-no-change-from", "--rect", "0,0,2,2", "--initial", "2", "--poll", "nonduration"}, "duration"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			group := autogenScreenCommands(open)
			cmd := findAutogenCommand(t, group, tc.args[0])
			cmd.SetArgs(tc.args[1:])
			cmd.SilenceUsage = true
			if err := cmd.ExecuteContext(context.Background()); err == nil || !strings.Contains(strings.ToLower(err.Error()), tc.want) {
				t.Fatalf("invalid generated CLI input accepted: %v", err)
			}
		})
	}
	if frames != 0 {
		t.Fatalf("invalid generated arguments read private capture %d times", frames)
	}
}

func findAutogenCommand(t *testing.T, commands []*cobra.Command, name string) *cobra.Command {
	t.Helper()
	for _, c := range commands {
		if c.Name() == name {
			return c
		}
	}
	t.Fatalf("missing generated command %q", name)
	return nil
}

func TestAutogeneratedCommandsUseActualSyntheticBackendAndWriteCompleteHash(t *testing.T) {
	pixels := pftest.SolidImage(2, 2, color.RGBA{R: 21, G: 32, B: 43, A: 255})
	want := fmt.Sprintf("%08x", find.PixelHash(pixels, nil))
	for _, tc := range []struct {
		name string
		args []string
	}{
		{"grab-full-hash", nil},
		{"wait-for-no-change", []string{"--rect", "0,0,2,2", "--stable", "1", "--poll", "1ms"}},
		{"wait-for-no-change-from", []string{"--rect", "0,0,2,2", "--initial", want, "--stable", "1", "--poll", "1ms"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			command := findAutogenCommand(t, autogenScreenCommands(func(context.Context) (*perfuncted.Session, error) {
				return pftest.New(&pftest.Screenshotter{Frames: []image.Image{pixels}}, nil, nil, nil), nil
			}), tc.name)
			var out bytes.Buffer
			command.SetArgs(tc.args)
			command.SetOut(&out)
			command.SilenceUsage = true
			ctx, cancel := context.WithTimeout(context.Background(), time.Second)
			defer cancel()
			if err := command.ExecuteContext(ctx); err != nil || strings.TrimSpace(out.String()) != want {
				t.Fatalf("generated command output=%q err=%v want=%q", out.String(), err, want)
			}
		})
	}
}

func TestAutogeneratedLiteralInputDispatchesActualBackend(t *testing.T) {
	typed := &pftest.Inputter{}
	command := findAutogenCommand(t, autogenInputCommands(func(context.Context) (*perfuncted.Session, error) { return pftest.New(nil, typed, nil, nil), nil }), "type-literal")
	command.SetArgs([]string{"{ctrl+x} copied literally"})
	if err := command.ExecuteContext(context.Background()); err != nil {
		t.Fatal(err)
	}
	if got := typed.Typed(); got != "{ctrl+x} copied literally" {
		t.Fatalf("literal command altered private text: %q", got)
	}
}

type deniedGeneratedOutput struct{}

func (deniedGeneratedOutput) Write([]byte) (int, error) { return 0, os.ErrPermission }
func TestAutogeneratedScreenOutputFailureCannotAcknowledgeHash(t *testing.T) {
	pixels := pftest.SolidImage(2, 2, color.RGBA{A: 255})
	cmd := findAutogenCommand(t, autogenScreenCommands(func(context.Context) (*perfuncted.Session, error) {
		return pftest.New(&pftest.Screenshotter{Frames: []image.Image{pixels}}, nil, nil, nil), nil
	}), "grab-full-hash")
	cmd.SetOut(deniedGeneratedOutput{})
	cmd.SilenceUsage = true
	if err := cmd.ExecuteContext(context.Background()); !errors.Is(err, os.ErrPermission) {
		t.Fatalf("unwritable output acknowledged success: %v", err)
	}
}

func TestAutogeneratedCommandsPropagateProviderFailureWithoutResult(t *testing.T) {
	for _, tc := range []struct {
		name    string
		args    []string
		isInput bool
	}{
		{"grab-full-hash", nil, false},
		{"wait-for-no-change", []string{"--rect", "0,0,2,2", "--stable", "1", "--poll", "1ms"}, false},
		{"wait-for-no-change-from", []string{"--rect", "0,0,2,2", "--initial", "1", "--stable", "1", "--poll", "1ms"}, false},
		{"type-literal", []string{"private input payload"}, true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			opener := func(ctx context.Context) (*perfuncted.Session, error) {
				if err := ctx.Err(); err != nil {
					return nil, err
				}
				if tc.isInput {
					return pftest.New(nil, &pftest.Inputter{Err: os.ErrPermission}, nil, nil), nil
				}
				return pftest.New(&pftest.Screenshotter{Err: os.ErrPermission}, nil, nil, nil), nil
			}
			var cmds []*cobra.Command
			if tc.isInput {
				cmds = autogenInputCommands(opener)
			} else {
				cmds = autogenScreenCommands(opener)
			}
			cmd := findAutogenCommand(t, cmds, tc.name)
			var out bytes.Buffer
			cmd.SetArgs(tc.args)
			cmd.SetOut(&out)
			cmd.SilenceUsage = true
			ctx, cancel := context.WithTimeout(context.Background(), time.Second)
			defer cancel()
			err := cmd.ExecuteContext(ctx)
			if !errors.Is(err, os.ErrPermission) || out.Len() != 0 {
				t.Fatalf("provider denied but result reported: %v out=%q", err, out.String())
			}
		})
	}
}

